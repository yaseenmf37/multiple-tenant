import fs from 'fs';
import path from 'path';

const sourceLocalePath = path.join(process.cwd(), 'locales', 'en');
const outputPath = path.join(process.cwd(), 'lib', 'i18n', 'types.ts');

console.log('Generating i18n types...');

try {
    const files = fs.readdirSync(sourceLocalePath);

    const namespaces = files
        .filter((file) => file.endsWith('.json'))
        .map((file) => path.parse(file).name);

    if (namespaces.length === 0) {
        throw new Error('No JSON files found in the source locale directory.');
    }

    let content = `// THIS FILE IS AUTO-GENERATED BY a script. DO NOT EDIT MANUALLY.\n\n`;

    namespaces.forEach((ns) => {
        content += `import type ${ns} from '@/locales/en/${ns}.json';\n`;
    });

    content += `import type { DotNestedKeys } from '@/types/utils';\n`;
    content += `import type { NAMESPACES } from './config';\n\n`;

    content += `// Define the master list of resources here.\n`;
    content += `export interface Resources {\n`;
    namespaces.forEach((ns) => {
        content += `  ${ns}: typeof ${ns};\n`;
    });
    content += `}\n\n`;

    content += `// Define the key-flattening logic here.\n`;
    content += `export type KeysForNamespace<N extends typeof NAMESPACES[number]> =\n`;
    namespaces.forEach((ns, index) => {
        content += `  N extends '${ns}'\n    ? DotNestedKeys<Resources['${ns}']>\n`;
        content += index === namespaces.length - 1 ? '    : never;\n' : '  : ';
    });

    fs.writeFileSync(outputPath, content, 'utf8');

    console.log(`Successfully generated i18n types at ${outputPath}`);
} catch (error) {
    console.error('Error generating i18n types:', error);
    process.exit(1);
}
